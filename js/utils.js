/**
 * Create star rating HTML
 */
export function createStars(rating, max = 5) {
  let html = '';
  for (let i = 1; i <= max; i++) {
    html += i <= rating ? Icons.star : Icons.starEmpty;
  }
  return `<div class="stars">${html}</div>`;
}
